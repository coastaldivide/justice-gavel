#!/usr/bin/env python3
"""Generate supabase/migrations/00000000000030_legal_accuracy_data.sql from research results.

Only records the research marked verified|corrected AND that name the page they were
checked against are written, and only those get verified_by/source_url — which is what
the API gate (routes/legaldata.js isVerifiedRow) requires before a row is shown.
"""
import json
import os
SP = os.path.join(os.path.dirname(__file__), '../../../docs/legal-research/2026-10')
OUT = os.path.join(os.path.dirname(__file__), '../../../') + 'supabase/migrations/00000000000030_legal_accuracy_data.sql'
VB = 'Source-checked 2026-10-26 (legal accuracy review; not attorney-reviewed)'

def q(v):
    if v is None: return 'NULL'
    if isinstance(v, bool): return 'TRUE' if v else 'FALSE'
    if isinstance(v, (int, float)): return repr(v)
    return "'" + str(v).replace("'", "''") + "'"

def first_url(u):
    if not u: return None
    u = str(u).split(' ; ')[0].split(';')[0].strip()
    return u if u.startswith('http') else None

ok = lambda r: r.get('status') in ('verified', 'corrected') and first_url(r.get('source_url'))
out = ["""BEGIN;
-- 00000000000030_legal_accuracy_data.sql — GENERATED by the Oct 2026 legal accuracy review
--
-- Writes the records that research checked against a source (statute text, official
-- agency page, or the CCRC / NCSL / RCFP / Justia references named in source_url).
-- Each written row gets source_url + verified_by + last_reviewed_at; the API serves
-- legal-rule rows ONLY when both are present (routes/legaldata.js isVerifiedRow), so
-- every row NOT written here stays hidden until it is checked. Not attorney-reviewed.
-- Idempotent: plain UPDATEs to fixed values; the two DELETEs target rows research
-- found to be fabricated (no such court exists).
"""]
cnt = {}
# ── statutes of limitation ─────────────────────────────────────────────
for f in ('sol_p1.json', 'sol_p2.json'):
    for r in json.load(open(f'{SP}/{f}'))['rows']:
        if not ok(r) or r.get('years') is None: continue
        note = (r.get('notes') or '').strip()
        if r.get('citation'): note = f"{note} ({r['citation']})"
        out.append(f"UPDATE statute_of_limitations SET years = {q(r['years'])}, notes = {q(note)}, source_url = {q(first_url(r['source_url']))}, "
                   f"verified_by = {q(VB)}, last_reviewed_at = '2026-10-26', updated_at = NOW() WHERE id = {int(r['id'])} AND state = {q(r['state'])};")
        cnt['sol'] = cnt.get('sol', 0) + 1
# ── drug penalties ─────────────────────────────────────────────────────
for f in ('drugs_p1.json', 'drugs_p2.json'):
    for r in json.load(open(f'{SP}/{f}'))['rows']:
        if not ok(r) or any(r.get(k) is None for k in ('min_days', 'max_days', 'max_fine')): continue
        note = (r.get('notes') or '').strip()
        if r.get('citation'): note = f"{note} ({r['citation']})"
        mn, mx = r['min_days'], r['max_days']
        out.append(
            f"UPDATE drug_penalties SET charge_level = {q(r.get('charge_level'))}, min_days = {q(mn)}, max_days = {q(mx)}, "
            f"min_fine = {q(r.get('min_fine') or 0)}, max_fine = {q(r['max_fine'])}, notes = {q(note)}, "
            f"source_url = {q(first_url(r['source_url']))}, verified_by = {q(VB)}, last_reviewed_at = '2026-10-26', updated_at = NOW() "
            f"WHERE id = {int(r['id'])} AND state = {q(r['state'])};")
        cnt['drugs'] = cnt.get('drugs', 0) + 1
# ── victim compensation ────────────────────────────────────────────────
vc = json.load(open(f'{SP}/contacts_vc_bar.json'))
for r in vc['victim_compensation']:
    if not ok(r): continue
    out.append(
        f"UPDATE victim_compensation SET program_name = {q(r.get('program_name'))}, phone = {q(r.get('phone'))}, url = {q(r.get('url'))}, "
        f"address = {q(r.get('address'))}, max_award = {q(r.get('max_award'))}, deadline_days = {q(r.get('deadline_days'))}, "
        f"covers = {q(json.dumps(r.get('covers')) if r.get('covers') else None)}, notes = {q(r.get('notes'))}, "
        f"source_url = {q(first_url(r['source_url']))}, verified_by = {q(VB)}, updated_at = NOW() WHERE id = {int(r['id'])} AND state = {q(r['state'])};")
    cnt['victim_comp'] = cnt.get('victim_comp', 0) + 1
# ── Hague central authorities ──────────────────────────────────────────
hs = json.load(open(f'{SP}/hague_specialty.json'))
out.append("ALTER TABLE hague_central_authorities ADD COLUMN IF NOT EXISTS us_partner BOOLEAN;")
for r in hs['hague_authorities']:
    if r.get('status') not in ('verified', 'corrected'): continue
    out.append(
        f"UPDATE hague_central_authorities SET contracting = {q(bool(r.get('contracting')))}, us_partner = {q(bool(r.get('us_partner')))}, "
        f"authority_name = COALESCE({q(r.get('authority_name'))}, authority_name), website = {q(r.get('website'))}, "
        f"phone = {q(r.get('phone'))}, source = 'HCCH Central Authority page + U.S. State Department partner list', "
        f"source_url = {q(first_url(r.get('source_url')) or r.get('status_table_url'))}, last_verified_at = '2026-10-26' WHERE country_code = {q(r['country_code'])};")
    cnt['hague'] = cnt.get('hague', 0) + 1
us = hs['us_central_authority']
out.append(
    "UPDATE hague_central_authorities SET hours_note = "
    + q('Business hours 8:15 a.m.–5:00 p.m. ET. To report an abduction in progress, call any time: 1-888-407-4747 (from the U.S. and Canada) or +1-202-501-4444 (from abroad).')
    + ", phone = '+1-202-501-4444', emergency_phone = '+1-888-407-4747', email = NULL, us_partner = NULL, source_url = "
    + q(us['source_url']) + ", last_verified_at = '2026-10-26' WHERE country_code = 'US';")
# ── immigration courts (resources) ─────────────────────────────────────
ho = json.load(open(f'{SP}/hotlines.json'))
for r in ho['resources']:
    if r.get('category') != 'IMMIGRATION_COURT' or r.get('status') not in ('verified', 'corrected'): continue
    if r.get('action') == 'remove' or 'remove_row' in (r.get('fields_changed') or []):
        out.append(f"DELETE FROM resources WHERE id = {int(r['id'])} AND category = 'IMMIGRATION_COURT';  -- {r.get('title')}: no such court (EOIR)")
        cnt['imm_removed'] = cnt.get('imm_removed', 0) + 1
        continue
    out.append(
        f"UPDATE resources SET title = COALESCE({q(r.get('title'))}, title), phone = {q(r.get('phone'))}, url = {q(r.get('url'))}, "
        f"website = {q(r.get('url'))}, address = {q(r.get('address'))}, state = COALESCE({q(r.get('state'))}, state), verified = 1, "
        f"updated_at = NOW() WHERE id = {int(r['id'])} AND category = 'IMMIGRATION_COURT';")
    cnt['imm_courts'] = cnt.get('imm_courts', 0) + 1
out.append('COMMIT;')
open(OUT, 'w').write('\n'.join(out) + '\n')
print(cnt)
