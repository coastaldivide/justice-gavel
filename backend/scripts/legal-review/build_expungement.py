#!/usr/bin/env python3
"""Build backend/src/routes/expungement/rules_data.js from the research results.

Every state/category gets the researched record when one exists. A record only
yields a verdict in the app when status is verified|corrected AND it has a
citation AND a source_url AND eligible is not null (enforced in rules.js).
States/categories with no research yet keep the old text but are marked
status 'unverified' with no citation, so the app shows no verdict for them.
"""
import json, glob, os, datetime
SP = os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../../docs/legal-research/2026-10')
REPO = os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../..')
old = json.load(open(f'{SP}/source_expungement_before.json'))
juv_old = {r['state']: r for r in json.load(open(f'{SP}/source_juvenile_before.json'))}
res = {}
for f in sorted(glob.glob(f'{SP}/expungement_g*.json')):
    for k, v in json.load(open(f)).items():
        if k.endswith('_domestic'):
            st = k.split('_')[0]
            res.setdefault('_extra', {})[st] = v
            continue
        res[k] = v
CATS = ['misdemeanor', 'felony', 'dui', 'dismissed', 'domestic', 'sexual']
FIELDS = ['eligible', 'waitYears', 'waitFrom', 'automatic', 'note', 'citation', 'source_url', 'status', 'varies']
out, juv, stats = {}, {}, {'researched': 0, 'verified': 0, 'corrected': 0, 'unverifiable': 0, 'unverified': 0}
for st in sorted(old):
    r = res.get(st)
    o = {'name': old[st]['name'], 'remedy': (r or {}).get('remedy')}
    for c in CATS:
        rec = (r or {}).get('categories', {}).get(c)
        if st in res.get('_extra', {}) and c == 'domestic':
            x = res['_extra'][st]
            rec = x.get('categories', {}).get('domestic', x) if isinstance(x, dict) else rec
        if rec:
            stats['researched'] += 1
            stats[rec.get('status', 'unverifiable')] = stats.get(rec.get('status', 'unverifiable'), 0) + 1
            o[c] = {k: rec.get(k) for k in FIELDS}
            if o[c]['status'] == 'unverifiable':
                o[c].update({'eligible': None, 'waitYears': None})
            if not o[c].get('note'):
                o[c]['note'] = "We haven't verified this state's rule for this kind of record yet. A local criminal defense lawyer, public defender or legal aid office can check it for you."
            if o[c].get('waitYears') is None:
                o[c].pop('waitYears')   # no number → absent (never a guessed 0)
        else:
            stats['unverified'] += 1
            prev = old[st].get(c, {})
            o[c] = {'eligible': prev.get('eligible'), 'waitYears': prev.get('waitYears'), 'waitFrom': None,
                    'automatic': None, 'note': prev.get('note'), 'citation': None, 'source_url': None,
                    'status': 'unverified', 'varies': None}
    out[st] = o
    j = (r or {}).get('juvenile')
    if j:
        juv[st] = {k: j.get(k) for k in ['automatic', 'when', 'notes', 'citation', 'source_url', 'status']}
    else:
        p = juv_old.get(st, {})
        juv[st] = {'automatic': None, 'when': None, 'notes': None, 'citation': None, 'source_url': None, 'status': 'unverified'}
today = datetime.date.today().isoformat()
js = f"""/**
 * expungement/rules_data.js — GENERATED by the Oct 2026 legal accuracy review. Do not hand-edit:
 * change the research results and regenerate (see docs/LEGAL_ACCURACY_REVIEW.md).
 *
 * One record per state × category. Fields: eligible (true | false | 'conditional' | null),
 * waitYears (may be a fraction: 0.25 = 3 months), waitFrom, automatic, note (plain English),
 * citation, source_url (the page the record was checked against), status
 * ('verified' | 'corrected' = checked against a source; 'unverifiable' | 'unverified' = NOT
 * checked, the app shows no verdict), varies (true = depends on offense/judge — say so).
 * None of it has been reviewed by a lawyer.
 * Generated {today}. Researched records: {stats['researched']} · not yet researched: {stats['unverified']}.
 */
export const STATE_RULES_DATA = {json.dumps(out, indent=1, ensure_ascii=False)};

/** Juvenile record sealing by state — same status rules. */
export const JUVENILE_SEALING_DATA = {json.dumps(juv, indent=1, ensure_ascii=False)};
"""
open(f'{REPO}/backend/src/routes/expungement/rules_data.js', 'w').write(js)
print(json.dumps(stats))
