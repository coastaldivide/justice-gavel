#!/usr/bin/env node
/**
 * build-guide-corpus.mjs — copies the app's sourced court guide ("Going to court: how to dress
 * and act") and "Your case, step by step" texts, in all eight languages, with their official
 * sources, into backend/src/data/guideCorpus.js so the AI can cite them (ai/legalCorpus.js).
 *
 * The words and sources live in the app (frontend/src/constants/{guideSources,courtGuide,
 * caseSteps}.ts + frontend/src/i18n/<lang>.json, docs/COURT_GUIDE.md); the backend is deployed
 * without the frontend, so it keeps a generated copy. guide_corpus.test.js re-runs this
 * generator and fails when the copy has drifted.
 *
 *   node backend/scripts/build-guide-corpus.mjs            write the file
 *   node backend/scripts/build-guide-corpus.mjs --check    exit 1 when the file is out of date
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '../..');
const FE = path.join(REPO, 'frontend/src');
const OUT = path.join(REPO, 'backend/src/data/guideCorpus.js');
export const LANGS = ['en', 'es', 'pt', 'vi', 'ht', 'zh', 'ar', 'tl'];

const read = (p) => fs.readFileSync(path.join(FE, p), 'utf8');

/** GUIDE_SOURCES from guideSources.ts: id → { org?, page?, labelKey?, url, checked }. */
function parseSources(src) {
  const checked = /GUIDE_CHECKED = '(\d{4}-\d{2}-\d{2})'/.exec(src)?.[1];
  if (!checked) throw new Error('GUIDE_CHECKED not found');
  const out = {};
  const re = /^\s*([a-z_]+):\s*\{([^\n]*)\},?\s*$/gm;
  let m;
  while ((m = re.exec(src))) {
    const body = m[2];
    const field = (k) => {
      const f = new RegExp(`${k}:\\s*(?:'((?:[^'\\\\]|\\\\.)*)'|"((?:[^"\\\\]|\\\\.)*)"|(null))`).exec(body);
      if (!f) return undefined;
      if (f[3] === 'null') return null;
      return (f[1] ?? f[2]).replace(/\\'/g, "'");
    };
    out[m[1]] = { org: field('org') ?? null, page: field('page') ?? null, labelKey: field('labelKey') ?? null, url: field('url') ?? null, checked };
  }
  if (Object.keys(out).length < 10) throw new Error('GUIDE_SOURCES not parsed');
  return out;
}

/** COURT_GUIDE sections: [{ id, count, sources }]. */
function parseGuide(src) {
  const out = [];
  const re = /\{\s*id:\s*'([a-z_]+)',\s*count:\s*(\d+),\s*sources:\s*\[([^\]]*)\]/g;
  let m;
  while ((m = re.exec(src))) out.push({ id: m[1], count: Number(m[2]), sources: [...m[3].matchAll(/'([a-z_]+)'/g)].map((x) => x[1]) });
  if (!out.length) throw new Error('COURT_GUIDE not parsed');
  return out;
}

/** caseSteps.ts SOURCES: [{ id, sources }] in catalog order. */
function parseStages(src, catalog) {
  const block = /const SOURCES[^{]*\{([\s\S]*?)\n\};/.exec(src)?.[1];
  if (!block) throw new Error('SOURCES not parsed');
  const map = {};
  for (const m of block.matchAll(/([a-z_]+):\s*\[([^\]]*)\]/g)) map[m[1]] = [...m[2].matchAll(/'([a-z_]+)'/g)].map((x) => x[1]);
  return catalog.stages.map((s) => ({ id: s.id, sources: map[s.id] || [] }));
}

export function buildCorpus() {
  const sources = parseSources(read('constants/guideSources.ts'));
  const guide = parseGuide(read('constants/courtGuide.ts'));
  const catalog = JSON.parse(read('constants/caseStepsCatalog.json'));
  const stages = parseStages(read('constants/caseSteps.ts'), catalog);
  const dict = Object.fromEntries(LANGS.map((l) => [l, JSON.parse(read(`i18n/${l}.json`))]));
  const tr = (key) => Object.fromEntries(LANGS.map((l) => {
    const v = dict[l][key] ?? dict.en[key];
    if (typeof v !== 'string' || !v.trim()) throw new Error(`missing i18n key ${key}`);
    return [l, v];
  }));
  for (const s of Object.values(sources)) if (s.labelKey) s.label = tr(s.labelKey);
  return {
    checked: Object.values(sources)[0].checked,
    sources,
    sections: guide.map((g) => ({
      id: g.id, sources: g.sources, title: tr(`cgd_${g.id}_title`),
      items: Object.fromEntries(LANGS.map((l) => [l, Array.from({ length: g.count }, (_, i) => tr(`cgd_${g.id}_${i + 1}`)[l])])),
    })),
    stages: stages.map((s) => ({ id: s.id, sources: s.sources, title: tr(`cst_${s.id}_title`), body: tr(`cst_${s.id}_body`) })),
  };
}

export function renderCorpus(corpus = buildCorpus()) {
  return `/**
 * data/guideCorpus.js — GENERATED by backend/scripts/build-guide-corpus.mjs. Do not hand-edit:
 * change the app's texts (frontend/src/i18n/*.json, constants/{guideSources,courtGuide,caseSteps}.ts)
 * and regenerate. The court guide sections and case stages in eight languages, with the official
 * pages each one comes from (checked ${corpus.checked}); cited by the AI (ai/legalCorpus.js).
 */
export const GUIDE_CORPUS = Object.freeze(${JSON.stringify(corpus, null, 1)});
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = renderCorpus();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('[guide-corpus] backend/src/data/guideCorpus.js is out of date — run node backend/scripts/build-guide-corpus.mjs'); process.exit(1); }
    console.log('[guide-corpus] up to date');
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`[guide-corpus] wrote ${path.relative(REPO, OUT)}`);
  }
}
