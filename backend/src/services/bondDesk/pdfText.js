/**
 * services/bondDesk/pdfText.js — text layout for Bond Desk PDFs that mix scripts.
 *
 * Neither pdfkit nor pdf-lib shapes Arabic or orders right-to-left text, and one font has
 * no Latin, Arabic and Chinese letters together. layoutParagraph() turns one paragraph of
 * logical-order text into lines of visual-order runs, each run tagged with the font that
 * draws it (fontFor), so a page or a form field can draw them left to right:
 *
 *   1. Arabic shaping: each letter becomes its isolated / initial / medial / final
 *      presentation form (Unicode Arabic Presentation Forms-A/B), and lam + alef become the
 *      lam-alef ligature. The table (assets/fonts/arabic-forms.json) is generated by
 *      backend/scripts/build-pdf-fonts.py from the Unicode decompositions and lists only
 *      forms the bundled Arabic font has.
 *   2. Bidi levels: a compact version of the Unicode Bidirectional Algorithm (UAX #9, rules
 *      P2–P3, W1–W7, N1–N2, I1–I2, L1–L2, mirroring) for one paragraph without explicit
 *      embeddings. Digits and Latin words inside Arabic stay left to right.
 *   3. Line breaking at spaces and between Chinese characters (a word longer than the line
 *      is broken by character), measured with the real fonts.
 *   4. Per line: reorder to visual order and split into runs by font.
 *
 * The bundled Chinese and Arabic fonts carry no GSUB/GPOS tables, so fontkit draws each
 * code point as is and does not re-shape or re-reverse what this module produced.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const FONT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../assets/fonts');
const FORMS_DATA = JSON.parse(fs.readFileSync(path.join(FONT_DIR, 'arabic-forms.json'), 'utf8'));
const hex = (h) => (h ? String.fromCodePoint(parseInt(h, 16)) : null);
/** base letter → [isolated, final, initial, medial] (null where the font has no such form) */
const FORMS = new Map(Object.entries(FORMS_DATA.forms).map(([k, v]) => [hex(k), v.map(hex)]));
/** alef variant → [isolated, final] lam-alef ligature */
const LAM_ALEF = new Map(Object.entries(FORMS_DATA.lamAlef).map(([k, v]) => [hex(k), v.map(hex)]));
const LAM = '\u0644';
const TATWEEL = '\u0640';

const isMark = (ch) => /\p{Mn}/u.test(ch);
/** Joining type: D (dual), R (right), C (join-causing), T (transparent), U (none). */
function joiningType(ch) {
  if (ch === TATWEEL) return 'C';
  if (isMark(ch)) return 'T';
  const f = FORMS.get(ch);
  if (!f) return 'U';
  if (f[2] || f[3]) return 'D';
  if (f[1]) return 'R';
  return 'U';
}
const joinsForward = (t) => t === 'D' || t === 'C';
const acceptsJoin = (t) => t === 'D' || t === 'R' || t === 'C';

/**
 * Arabic shaping. → [{ out, src }] in logical order: `out` is what to draw (a presentation
 * form, a ligature, or the character itself), `src` the original character(s).
 */
export function shapeArabic(text) {
  const chars = [...text];
  const types = chars.map(joiningType);
  const prevIdx = (i) => { for (let j = i - 1; j >= 0; j--) if (types[j] !== 'T') return j; return -1; };
  const nextIdx = (i) => { for (let j = i + 1; j < chars.length; j++) if (types[j] !== 'T') return j; return -1; };
  const units = [];
  for (let i = 0; i < chars.length; i++) {
    const ch = chars[i];
    const t = types[i];
    if (t === 'U' || t === 'T' || t === 'C') { units.push({ out: ch, src: ch }); continue; }
    const p = prevIdx(i);
    const n = nextIdx(i);
    const fromPrev = p >= 0 && joinsForward(types[p]) && acceptsJoin(t);
    // lam + alef → one ligature (only when nothing sits between them)
    if (ch === LAM && n === i + 1 && LAM_ALEF.has(chars[n])) {
      const lig = LAM_ALEF.get(chars[n])[fromPrev ? 1 : 0];
      if (lig) {
        units.push({ out: lig, src: ch + chars[n] });
        types[n] = 'R';   // the ligature ends like an alef: it does not join the next letter
        i = n;
        continue;
      }
    }
    const toNext = t === 'D' && n >= 0 && acceptsJoin(types[n]);
    const f = FORMS.get(ch);
    const slot = fromPrev && toNext ? 3 : fromPrev ? 1 : toNext ? 2 : 0;
    units.push({ out: f[slot] || f[0] || ch, src: ch });
  }
  return units;
}

// ── Bidi classes ─────────────────────────────────────────────────────────────

const ARABIC_LETTER = /[\u0600-\u07BF\u0860-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]/;
const HEBREW = /[\u0590-\u05FF\uFB1D-\uFB4F]/;
/** Bidi class of a logical character (the subset of UAX #9 classes this module needs). */
export function bidiClass(ch) {
  const c = ch.codePointAt(0);
  if (ch === '\t' || ch === ' ' || ch === '\u3000') return 'WS';
  if (c >= 0x30 && c <= 0x39) return 'EN';
  if (c >= 0x06F0 && c <= 0x06F9) return 'EN';
  if ((c >= 0x0660 && c <= 0x0669) || c === 0x066B || c === 0x066C) return 'AN';
  if (isMark(ch)) return 'NSM';
  if (ch === '+' || ch === '-' || ch === '\u2212') return 'ES';
  if ('#$%\u00A2\u00A3\u00A4\u00A5\u00B0\u00B1\u066A\u20AC'.includes(ch)) return 'ET';
  if (',./:\u00A0\u060C\u202F'.includes(ch)) return 'CS';
  if (ch === '\u061B' || ch === '\u061F') return 'ON';
  if (ARABIC_LETTER.test(ch)) return 'AL';
  if (HEBREW.test(ch)) return 'R';
  if (/[\p{L}\p{Mc}\p{Nd}]/u.test(ch)) return 'L';
  return 'ON';
}

const MIRROR = { '(': ')', ')': '(', '[': ']', ']': '[', '{': '}', '}': '{', '<': '>', '>': '<', '\u00AB': '\u00BB', '\u00BB': '\u00AB', '\u2039': '\u203A', '\u203A': '\u2039' };

/** Paragraph embedding level from the first strong character (P2–P3): 0 = LTR, 1 = RTL. */
export function paragraphLevel(classes) {
  for (const c of classes) {
    if (c === 'L') return 0;
    if (c === 'R' || c === 'AL') return 1;
  }
  return 0;
}

/** Resolved embedding levels (W1–W7, N1–N2, I1–I2) for one paragraph. */
export function resolveLevels(classes, paraLevel) {
  const n = classes.length;
  const t = classes.slice();
  const sos = paraLevel ? 'R' : 'L';
  // W1: NSM takes the type of the previous character
  for (let i = 0; i < n; i++) if (t[i] === 'NSM') t[i] = i ? t[i - 1] : sos;
  // W2: EN after AL becomes AN; W3: AL → R
  let lastStrong = sos;
  for (let i = 0; i < n; i++) {
    if (t[i] === 'L' || t[i] === 'R' || t[i] === 'AL') lastStrong = t[i];
    else if (t[i] === 'EN' && lastStrong === 'AL') t[i] = 'AN';
  }
  for (let i = 0; i < n; i++) if (t[i] === 'AL') t[i] = 'R';
  // W4: a single separator between two numbers of the same kind
  for (let i = 1; i < n - 1; i++) {
    if (t[i] === 'ES' && t[i - 1] === 'EN' && t[i + 1] === 'EN') t[i] = 'EN';
    else if (t[i] === 'CS' && t[i - 1] === 'EN' && t[i + 1] === 'EN') t[i] = 'EN';
    else if (t[i] === 'CS' && t[i - 1] === 'AN' && t[i + 1] === 'AN') t[i] = 'AN';
  }
  // W5: terminators next to European numbers
  for (let i = 0; i < n; i++) {
    if (t[i] !== 'ET') continue;
    let j = i;
    while (j < n && t[j] === 'ET') j++;
    if ((i > 0 && t[i - 1] === 'EN') || (j < n && t[j] === 'EN')) for (let k = i; k < j; k++) t[k] = 'EN';
    i = j - 1;
  }
  // W6: the remaining separators and terminators are neutral
  for (let i = 0; i < n; i++) if (t[i] === 'ES' || t[i] === 'ET' || t[i] === 'CS') t[i] = 'ON';
  // W7: EN after L (or at the start of an LTR paragraph) is L
  lastStrong = sos;
  for (let i = 0; i < n; i++) {
    if (t[i] === 'L' || t[i] === 'R') lastStrong = t[i];
    else if (t[i] === 'EN' && lastStrong === 'L') t[i] = 'L';
  }
  // N1–N2: neutrals between two strong types of the same direction take it, else the embedding direction
  const dirOf = (x) => (x === 'L' ? 'L' : x === 'R' || x === 'EN' || x === 'AN' ? 'R' : null);
  for (let i = 0; i < n; i++) {
    if (dirOf(t[i])) continue;
    let j = i;
    while (j < n && !dirOf(t[j])) j++;
    const before = i > 0 ? dirOf(t[i - 1]) : sos;
    const after = j < n ? dirOf(t[j]) : sos;
    const d = before === after ? before : sos;
    for (let k = i; k < j; k++) t[k] = d;
    i = j - 1;
  }
  // I1–I2
  return t.map((x) => {
    if (paraLevel === 0) return x === 'R' ? 1 : x === 'AN' || x === 'EN' ? 2 : 0;
    return x === 'L' || x === 'AN' || x === 'EN' ? 2 : 1;
  });
}

/** L2: indices in visual order for the given levels. */
export function visualOrder(levels) {
  const idx = levels.map((_, i) => i);
  if (!levels.length) return idx;
  const max = Math.max(...levels);
  const minOdd = Math.min(...levels.filter((l) => l % 2 === 1), Infinity);
  if (minOdd === Infinity) return idx;
  for (let lvl = max; lvl >= minOdd; lvl--) {
    for (let i = 0; i < idx.length; i++) {
      if (levels[idx[i]] < lvl) continue;
      let j = i;
      while (j < idx.length && levels[idx[j]] >= lvl) j++;
      const seg = idx.slice(i, j).reverse();
      idx.splice(i, j - i, ...seg);
      i = j - 1;
    }
  }
  return idx;
}

// ── Layout ──────────────────────────────────────────────────────────────────

const HAN = /[\u2E80-\u2FFF\u3000-\u30FF\u3400-\u4DBF\u4E00-\u9FFF\uF900-\uFAFF\uFF00-\uFFEF]|[\u{20000}-\u{3FFFF}]/u;

/**
 * Lay out one paragraph (no line breaks inside).
 *   fontFor(ch) → font key that draws the (shaped) character, e.g. 'latin' | 'arabic' | 'cjk'
 *   measure(fontKey, string) → width in points
 *   width: available line width (Infinity: one line)
 *   direction: 'auto' (the first strong character decides, as dir="auto" does) or 'ltr'
 * → { rtl, arabicOnly, lines: [{ width, runs: [{ font, text, width }] }] } — runs in visual order.
 */
export function layoutParagraph(text, { fontFor, measure, width = Infinity, direction = 'auto' }) {
  const units = shapeArabic(text).map((u) => {
    const first = [...u.src][0];
    return { ...u, cls: bidiClass(first), font: fontFor([...u.out][0]) };
  });
  const classes = units.map((u) => u.cls);
  const paraLevel = direction === 'ltr' ? 0 : paragraphLevel(classes);
  const levels = resolveLevels(classes, paraLevel);
  units.forEach((u, i) => { u.level = levels[i]; });
  const arabicOnly = paraLevel === 1 && !classes.includes('L');

  // Segments: the pieces a line may break between (a word plus its trailing spaces, or one Han character).
  const segments = [];
  let cur = [];
  const push = () => { if (cur.length) segments.push(cur); cur = []; };
  for (let i = 0; i < units.length; i++) {
    const u = units[i];
    const han = HAN.test(u.src);
    if (han && cur.length && cur.some((x) => x.cls !== 'WS')) push();
    cur.push(u);
    const next = units[i + 1];
    if (!next) break;
    if (u.cls === 'WS' && next.cls !== 'WS') push();
    else if (han && next.cls !== 'WS' && !isMark(next.src)) push();
  }
  push();
  const runWidth = (us) => {
    let w = 0;
    for (let i = 0; i < us.length;) {
      let j = i;
      while (j < us.length && us[j].font === us[i].font) j++;
      w += measure(us[i].font, us.slice(i, j).map((u) => u.out).join(''));
      i = j;
    }
    return w;
  };
  const trimmedWidth = (us) => {
    let end = us.length;
    while (end > 0 && us[end - 1].cls === 'WS') end--;
    return runWidth(us.slice(0, end));
  };

  const lines = [];
  let line = [];
  for (let seg of segments) {
    if (line.length && trimmedWidth([...line, ...seg]) > width) { lines.push(line); line = []; }
    // a single word longer than the line: break it by character
    while (!line.length && trimmedWidth(seg) > width && seg.length > 1) {
      let k = 1;
      while (k < seg.length && trimmedWidth(seg.slice(0, k + 1)) <= width) k++;
      while (k < seg.length && isMark(seg[k].src)) k++;
      lines.push(seg.slice(0, k));
      seg = seg.slice(k);
    }
    line.push(...seg);
  }
  if (line.length || !lines.length) lines.push(line);

  return {
    rtl: paraLevel === 1,
    arabicOnly,
    lines: lines.map((us) => {
      // L1: trailing whitespace goes to the paragraph level, then is dropped from the drawing
      let end = us.length;
      while (end > 0 && us[end - 1].cls === 'WS') end--;
      const vis = us.slice(0, end);
      const order = visualOrder(vis.map((u) => u.level));
      const seq = order.map((i) => {
        const u = vis[i];
        const out = u.level % 2 === 1 && MIRROR[u.out] ? MIRROR[u.out] : u.out;
        return { ...u, out };
      });
      // keep each combining mark after its base so it is drawn over it
      for (let i = 0; i < seq.length; i++) {
        if (!isMark(seq[i].src) || seq[i].level % 2 === 0) continue;
        let j = i;
        while (j < seq.length && isMark(seq[j].src)) j++;
        if (j === seq.length) break;
        const marks = seq.splice(i, j - i);   // the base is now at i
        seq.splice(i + 1, 0, ...marks);
        i += marks.length;
      }
      const runs = [];
      for (const u of seq) {
        const last = runs[runs.length - 1];
        if (last && last.font === u.font) last.text += u.out;
        else runs.push({ font: u.font, text: u.out });
      }
      for (const r of runs) r.width = measure(r.font, r.text);
      return { runs, width: runs.reduce((s, r) => s + r.width, 0) };
    }),
  };
}
