import { safeJson, safeInt } from '../../utils/routeHelpers.js';
import { msg, resolveLang } from '../../i18n/index.js';
/**
 * motions/history.js — GET /history, GET|DELETE /history/:id,
 * GET /history/:id/document?format=docx|pdf — the saved draft as Word / PDF (AI step 5,
 * services/draftDocs): the notice on every page, the case details as typed, a blank signature
 * line; the app has no checked source for case law or motion statutes, so every paragraph that
 * names a statute, rule or case is withheld ("No source found for this part — not shown") —
 * the attorney adds the authorities from a primary source. The draft in the app is unchanged.
 */
import { Router }         from 'express';
import { authRequired }   from '../../middleware/auth.js';
import { getDb }          from '../../db/index.js';
import logger             from '../../utils/logger.js';
import { MOTION_TYPES }   from './_motion_types.js';
import { buildModel, sendDocument, FORMATS } from '../../services/draftDocs/index.js';
import { makeUserLimiter } from '../../middleware/sharedAiLimiter.js';

const downloadLimiter = makeUserLimiter({ windowMs: 3_600_000, max: 60, message: (req) => msg(resolveLang(req), 'docs.err.limit') });
/** The motion's case details the person typed, in a fixed order (only these keys; values verbatim). */
export const MOTION_FIELDS = ['defendant_name', 'case_number', 'court_name', 'state', 'county', 'attorney_name', 'bar_number', 'facts', 'additional_notes'];

/** A motion_history row → the document model. */
export function motionModel(row, lang) {
  const fields = safeJson(row.case_fields, {}) || {};
  const label = MOTION_TYPES[row.motion_type]?.label || row.motion_type;
  return buildModel({
    title: msg(lang, 'docs.motion_title', { motion: label }), lang, draft: row.draft,
    allowed: [], sources: [],
    fields: MOTION_FIELDS.map((k) => ({ label: msg(lang, `docs.field.${k}`), value: typeof fields[k] === 'string' || typeof fields[k] === 'number' ? String(fields[k]) : '' })),
    signerName: typeof fields.attorney_name === 'string' ? fields.attorney_name : '',
  });
}

// UPL compliance: all AI-generated motions carry this disclaimer
const MOTION_DISCLAIMER = 'This motion was generated by AI as a legal template only. It is not legal advice. Always review with a licensed attorney before filing.';




const router = Router();



router.get('/history', authRequired, async (req, res) => {
  try {
    const db = await getDb();
    const _histPage = Math.max(0, safeInt(req.query.page || '0'));
    const rows = await db.all(
      `SELECT id, motion_type, paid_cents, created_at, filing_status, filed_at,
              substr(draft, 1, 200) as preview
       FROM motion_history WHERE user_id=? ORDER BY created_at DESC LIMIT 20 OFFSET ${Math.max(0,safeInt(req.query.page||'0'))*20}`,
      [req.user.id]
    );
    const enriched = rows.map(r => ({
      ...r,
      label: MOTION_TYPES[r.motion_type]?.label || r.motion_type,
      icon:  MOTION_TYPES[r.motion_type]?.icon  || '📄',
    }));
    res.json(enriched);
  } catch (e) {
    logger.error('[motions/history]', e.message);
    res.status(500).json({ error: 'server_error', code: 'server_error', message: msg(resolveLang(req), 'motions.err.server') });
  }
});

// ── GET /api/motions/history/:id ──────────────────────────────────────────────
router.get('/history/:id', authRequired, async (req, res) => {
  try {
    const db = await getDb();
    const row = await db.get(
      'SELECT id, user_id, motion_type, case_fields, draft, filing_status, filed_at, paid_cents, created_at FROM motion_history WHERE id=? AND user_id=? LIMIT 1',
      [safeInt(req.params.id), req.user.id]
    );
    if (!row) return res.status(404).json({ error: 'not_found', code: 'not_found', message: msg(resolveLang(req), 'motions.err.not_found') });
    res.json({ not_legal_advice: true, disclaimer: MOTION_DISCLAIMER, ...row, case_fields: safeJson(row.case_fields, {}) });
  } catch (e) {
    logger.error('[motions/history/:id]', e.message);
    res.status(500).json({ error: 'server_error', code: 'server_error', message: msg(resolveLang(req), 'motions.err.server') });
  }
});

// ── GET /api/motions/history/:id/document?format=docx|pdf ─────────────────────
router.get('/history/:id/document', authRequired, downloadLimiter, async (req, res) => {
  const lang = resolveLang(req);
  const format = String(req.query.format || '').toLowerCase();
  if (!FORMATS.includes(format)) return res.status(400).json({ error: 'bad_format', code: 'bad_format', message: msg(lang, 'docs.err.format') });
  try {
    const db = await getDb();
    const row = await db.get('SELECT id, motion_type, case_fields, draft FROM motion_history WHERE id=? AND user_id=? LIMIT 1', [safeInt(req.params.id), req.user.id]);
    if (!row) return res.status(404).json({ error: 'not_found', code: 'not_found', message: msg(lang, 'motions.err.not_found') });
    return await sendDocument(res, motionModel(row, lang), format, { base: `motion-${row.motion_type}`, id: row.id });
  } catch (e) {
    logger.error({ err: e.message }, '[motions/history/document]');
    res.status(500).json({ error: 'server_error', code: 'server_error', message: msg(lang, 'docs.err.server') });
  }
});

// ── DELETE /api/motions/history/:id ──────────────────────────────────────────
router.delete('/history/:id', authRequired, async (req, res) => {
  try {
    const db = await getDb();
    const r = await db.run('DELETE FROM motion_history WHERE id=? AND user_id=?', [safeInt(req.params.id), req.user.id]);
    if (!r.changes) return res.status(404).json({ error: 'not_found', code: 'not_found', message: msg(resolveLang(req), 'motions.err.not_found') });
    res.json({ ok: true });
  } catch (e) {
    logger.error('[motions/history/delete]', e.message);
    res.status(500).json({ error: 'server_error', code: 'server_error', message: msg(resolveLang(req), 'motions.err.server') });
  }
});

export default router;
